/// Whether a label names a sound or a person rather than a taxon: one of
/// [`SOUND_CLASSES`], or a human class ([`names_a_human`]).
#[must_use]
pub fn is_sound_class(scientific_name: &str, common_name: &str) -> bool {
    let sci = scientific_name.trim();
    names_a_human(sci, common_name)
        || SOUND_CLASSES
            .iter()
            .any(|class| class.eq_ignore_ascii_case(sci))
}
