//! Labels that name a sound rather than a taxon (MMP-04, ACC-18).
//!
//! The classifiers' vocabularies are not taxa only. BirdNET V2.4 carries
//! `Dog`, `Engine`, `Siren` and five more besides its three human classes;
//! Perch v2 carries 198 `AudioSet` sound classes (`Speech`, `Engine`, `Crow`,
//! `Rain`, …) beside its species. Such a label is evidence about the
//! recording, which the noise and privacy filters use, and never a species: a
//! row named `Engine` would sit in the species list, the life list and every
//! count of richness, and be posted to `BirdWeather` with the station's
//! location. The detection daemon therefore never emits one as a detection.
//! The maintainer chose this over BirdNET-Pi's behaviour, which stores any
//! label over `CONFIDENCE` that passes its lists (`scripts/utils/analysis.py`
//! at `88985a3`), on 2026-11-23.
//!
//! The list is named, not inferred: "no space in the scientific name" would
//! also catch BirdNET+ V3.0's genus-level taxa (`Acris`, `Bufo`). A test holds
//! it to the bundled label files.

